-- Состояние движка на ноде, отдельно от состояния агента.
--
-- Это разные вещи, и их смешение дорого обходится: агент может исправно
-- отвечать панели, пока Xray на той же машине лежит и не пускает ни
-- одного клиента. В панели такая нода выглядела «online», и понять, что
-- она никого не обслуживает, было нельзя — приходилось лезть по SSH.
--
-- engine_ok    — поднялся ли движок и работает ли сейчас;
-- engine_error — причина, которую он назвал (обрезанная до разумного).

ALTER TABLE nodes ADD COLUMN IF NOT EXISTS engine_ok    boolean NOT NULL DEFAULT true;
ALTER TABLE nodes ADD COLUMN IF NOT EXISTS engine_error text;
