-- Имя ноды занимала и удалённая запись.
--
-- Удаление ноды — мягкое: строка остаётся и помечается deleted_at, чтобы
-- сохранить историю трафика и платежей за сервер. Но ограничение на name
-- было обычным, поэтому имя удалённой ноды оставалось занятым навсегда:
-- человек удалял «Germani», заводил её заново и упирался в «запись с таким
-- значением уже существует», не понимая, откуда она есть.
--
-- Уникальность теперь распространяется только на живые записи. Две
-- удалённые могут делить имя — это уже история, а не рабочий список.

ALTER TABLE nodes DROP CONSTRAINT IF EXISTS nodes_name_key;

-- Если в базе уже накопились удалённые тёзки, индекс на живых строках
-- всё равно построится: он их не видит.
CREATE UNIQUE INDEX IF NOT EXISTS nodes_name_live_key
    ON nodes (name)
    WHERE deleted_at IS NULL;
