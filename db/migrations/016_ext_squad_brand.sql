--  настроек панели: иначе все партнёры выглядели бы одинаково и
--  выдавали бы вашу марку своим клиентам.
-- ═══════════════════════════════════════════════════════════════════

ALTER TABLE external_squads
    ADD COLUMN IF NOT EXISTS brand_name  text,
    ADD COLUMN IF NOT EXISTS support_url text,
    ADD COLUMN IF NOT EXISTS logo_url    text,
    -- Публичный адрес страницы подписки потребителя. Панель по нему
    -- ничего не делает, но показывает — чтобы было видно, где живёт
    -- витрина этого партнёра.
    ADD COLUMN IF NOT EXISTS page_url    text;
