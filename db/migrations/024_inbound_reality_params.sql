-- Параметры Reality — из профиля, а не из копии в хосте.
--
-- Публичный ключ и short id клиент обязан назвать ровно те, что стоят на
-- сервере: иначе рукопожатие Reality не проходит и локация выглядит
-- нерабочей. До сих пор они хранились в строке хоста, куда попадали при
-- его создании. Стоило перевыпустить ключи в профиле или привязать хост
-- к инбаунду другого профиля — и значения расходились. Снаружи это
-- выглядело как «сервер не отвечает», а в конфигах всё было «на месте».
--
-- Теперь источник один — профиль. Панель разбирает его при сохранении и
-- кладёт параметры сюда, рядом с остальными полями инбаунда. Публичный
-- ключ выводится из приватного, поэтому разойтись им уже негде.
--
-- Поля в hosts остаются: они позволяют задать своё значение для
-- конкретной локации. Пусто — берётся из инбаунда.

ALTER TABLE inbounds
    ADD COLUMN IF NOT EXISTS public_key text,
    ADD COLUMN IF NOT EXISTS short_id   text,
    ADD COLUMN IF NOT EXISTS sni        text;

COMMENT ON COLUMN inbounds.public_key IS
    'Публичный ключ Reality, выведенный из privateKey профиля.';
COMMENT ON COLUMN inbounds.short_id IS
    'Первый shortId из профиля. Клиент обязан назвать один из списка сервера.';
COMMENT ON COLUMN inbounds.sni IS
    'serverNames[0] профиля — имя, под которое маскируется Reality.';
