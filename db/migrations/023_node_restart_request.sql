-- Перезапуск движка по команде из панели.
--
-- До сих пор Xray перезапускался только сам: при смене конфига или
-- состава клиентов. Если он завис, отвалился от сети или подхватил
-- обновлённый сертификат — сделать с этим из панели было нечего, надо
-- было идти на сервер руками.
--
-- Панель ставит отметку времени, агент видит её при очередном опросе и
-- перезапускает движок. Отметка не сбрасывается: агент помнит, какую он
-- уже отработал, и по одному нажатию перезапускает ровно один раз.

ALTER TABLE nodes
    ADD COLUMN IF NOT EXISTS restart_requested_at timestamptz;

COMMENT ON COLUMN nodes.restart_requested_at IS
    'Когда из панели попросили перезапустить движок. Агент сравнивает с отработанной.';
