INSERT INTO settings (key, value) VALUES
    -- Имя подписки в списке приложения. Пусто — соберём из названия
    -- бренда и имени клиента, как было раньше.
    ('subscription.profile_title',         '""'),
    -- Как часто приложение само перечитывает подписку, в часах.
    ('subscription.update_interval_hours', '12'),
    -- Баннер в приложении. Пусто — баннера нет.
    ('subscription.announce',              '""')
ON CONFLICT (key) DO NOTHING;

-- ── Ремарки-заглушки ─────────────────────────────────────────────────
--  Когда подписка не активна, приложение всё равно показывает список
--  локаций. Вместо конфигов кладём туда объяснение — это единственное
--  место, где человек его точно увидит, даже не открывая бота.
--  Плейсхолдеры: {date} — дата окончания, {days} — сколько дней прошло
--  или осталось, {tariff} — название тарифа.
INSERT INTO settings (key, value) VALUES
    ('subscription.remark_expired',  '"⛔ Подписка истекла {date}"'),
    ('subscription.remark_limited',  '"📉 Трафик закончился"'),
    ('subscription.remark_disabled', '"🚫 Доступ приостановлен"'),
    ('subscription.remark_no_hosts', '"Нет доступных локаций"'),

-- ── Поведение ────────────────────────────────────────────────────────
    -- Неизвестный клиент по умолчанию получает base64-список ссылок:
    -- его понимают почти все. Тумблер переключает на Xray JSON.
    ('subscription.json_on_unknown_ua', 'false'),
    -- Имя клиента в заголовке ответа — для отладки интеграций.
    ('subscription.username_header',    'true'),
    -- Перемешивать локации: иначе все клиенты идут в первую по порядку.
    ('subscription.shuffle_hosts',      'false')
ON CONFLICT (key) DO NOTHING;
