--  Валюта системы.
--
--  Сервис работает в одной валюте: тарифы, цены, отчёты и выплаты —
--  всё в ней. Несколько валют одновременно означали бы курс, пересчёт
--  и расхождения в отчётности, а продавцу нужно ровно одно значение.
--
--  Единственное исключение — Telegram Stars: они существуют только в
--  собственных единицах и рубли принять не могут. Поэтому у тарифа
--  может быть дополнительная цена в XTR, и это осознанное исключение,
--  а не вторая валюта системы.
-- ═══════════════════════════════════════════════════════════════════

INSERT INTO settings (key, value) VALUES
    ('billing.currency', '"USD"')
ON CONFLICT (key) DO NOTHING;
