-- Хост без инбаунда.
--
-- Конфиг профиля переписывают целиком — вставляют из другой панели, из
-- статьи, правят теги. Инбаунд, на который ссылался хост, при этом
-- пропадает. Раньше сохранение в такой ситуации отвергалось: база не
-- давала удалить занятую строку, и наружу шла «внутренняя ошибка».
--
-- Правильнее не держать человека: конфиг сохраняется, а хост остаётся
-- на месте, но без привязки — со своим адресом, портом и названием,
-- которые заново набирать не нужно. Его видно в списке с пометкой, и
-- одним действием он привязывается к новому инбаунду.
--
-- Выдаче подписок это ничем не грозит: все запросы соединяют хосты с
-- инбаундами через INNER JOIN, и отвязанный просто не попадает в выдачу.

ALTER TABLE hosts ALTER COLUMN inbound_id DROP NOT NULL;

COMMENT ON COLUMN hosts.inbound_id IS
    'Инбаунд профиля. NULL — привязка слетела при замене конфига, хост ждёт новой.';

-- Владельца задаём явно: миграции запускают от postgres, и приложение
-- иначе получит «permission denied» ровно в момент нажатия кнопки.
DO $$
DECLARE app_role text := current_setting('sn.app_role', true);
BEGIN
    IF app_role IS NULL OR app_role = '' THEN
        SELECT pg_get_userbyid(datdba) INTO app_role FROM pg_database WHERE datname = current_database();
    END IF;
    EXECUTE format('ALTER TABLE hosts OWNER TO %I', app_role);
END $$;
