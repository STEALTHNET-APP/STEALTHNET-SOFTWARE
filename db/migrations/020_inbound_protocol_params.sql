-- Параметры инбаунда, без которых клиент не соберёт рабочее подключение.
--
-- method — метод шифрования shadowsocks. Клиент обязан назвать ровно тот
-- же, иначе рукопожатие не состоится.
--
-- service_name — имя сервиса gRPC. Без него транспорт grpc в клиентском
-- конфиге пустой: подключение уходит «в никуда» и молча не работает.
--
-- Оба значения задаются на сервере, в конфиге профиля, поэтому вытаскиваем
-- их оттуда при сохранении, а не просим вводить руками во второй раз.

ALTER TABLE inbounds ADD COLUMN IF NOT EXISTS method       text;
ALTER TABLE inbounds ADD COLUMN IF NOT EXISTS service_name text;

-- Серверный ключ shadowsocks-2022. В многопользовательском режиме клиент
-- подключается парой «серверный ключ:личный ключ», поэтому ключ нужен и
-- на стороне выдачи подписок, а не только в конфиге ноды.
ALTER TABLE inbounds ADD COLUMN IF NOT EXISTS server_key text;
