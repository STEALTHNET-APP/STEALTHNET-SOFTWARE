-- ═══════════════════════════════════════════════════════════════════
--  Иконки приложений на странице подписки.
--
--  По умолчанию используем собственный набор SVG, нарисованный для этого
--  проекта. Готовые паки иконок из интернета брать нельзя: популярные
--  наборы выложены БЕЗ ЛИЦЕНЗИИ, а это значит «все права защищены».
--
--  Поэтому даём администратору два способа поставить свои:
--    * icon_url — ссылка на картинку (если он вправе её использовать);
--    * icon_svg — вставленный SVG целиком.
--  Заполнено — берём его, пусто — рисуем встроенную.
--
--  ⚠️ icon_url создаёт внешний запрос со страницы подписки. Её открывают
--  из-под блокировок, поэтому предпочтителен icon_svg: он инлайнится
--  в HTML и работает всегда.
-- ═══════════════════════════════════════════════════════════════════

ALTER TABLE subscription_page_apps
    ADD COLUMN IF NOT EXISTS icon_url text,
    ADD COLUMN IF NOT EXISTS icon_svg text;

COMMENT ON COLUMN subscription_page_apps.icon_svg IS
    'Инлайновый SVG. Предпочтительнее icon_url: не требует внешнего запроса.';
