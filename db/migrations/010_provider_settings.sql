--  Настройки платёжных модулей, которые задаёт администратор.
--
--  Часть свойств модуля — факты о коде и окружении: какие валюты он
--  умеет и настроены ли у него ключи. Их пишет сам модуль при старте.
--  Остальное — решение администратора, и его перезапись при рестарте
--  выглядела бы как «настроил, а после обновления всё вернулось».
-- ═══════════════════════════════════════════════════════════════════

-- Какие из валют модуля реально предлагать клиенту. NULL — все, какие
-- модуль умеет. Нужно, когда одна валюта принимается несколькими
-- системами, а показывать в боте хочется одну.
ALTER TABLE payment_providers
    ADD COLUMN IF NOT EXISTS enabled_currencies text[];

-- Заметка администратора: чем этот модуль отличается от соседнего,
-- какая у него комиссия, кому писать при сбоях.
ALTER TABLE payment_providers
    ADD COLUMN IF NOT EXISTS note text;
