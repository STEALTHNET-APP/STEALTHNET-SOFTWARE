function translateTextNode(n){
  if(n.parentElement?.closest(I18N_SKIP))return;
  const raw=n.nodeValue,t=raw.trim();if(!t)return;
  const value=translatedText(t);if(value!==t)n.nodeValue=raw.replace(t,value);
}
function translateAttributes(el){
  if(el.closest?.('[translate="no"],[data-no-i18n]'))return;
  for(const name of ATTRS){const value=el.getAttribute(name);if(!value)continue;const next=translatedText(value);if(next!==value)el.setAttribute(name,next);}
}
function translateNode(root){
  if(LANG==='ru'||!root)return;
  if(root.nodeType===Node.TEXT_NODE){translateTextNode(root);return;}
  if(root.nodeType!==Node.ELEMENT_NODE)return;
  translateAttributes(root);
  for(const link of [...(root.matches('a[href]')?[root]:[]),...root.querySelectorAll('a[href]')]){
    const href=link.getAttribute('href');
    if(/^\/?(?:cabinet|subscription)-installation\.html$/.test(href))link.setAttribute('href',href.replace('.html','-en.html'));
  }
  const walker=document.createTreeWalker(root,NodeFilter.SHOW_TEXT);while(walker.nextNode())translateTextNode(walker.currentNode);
  for(const el of root.querySelectorAll('['+ATTRS.join('],[')+']'))translateAttributes(el);
}
function watchI18n(){
  if(LANG==='ru')return;
  const obs=new MutationObserver(muts=>{
    for(const m of muts){
      if(m.type==='attributes')translateAttributes(m.target);
      else if(m.type==='characterData')translateTextNode(m.target);
      else for(const n of m.addedNodes)translateNode(n);
    }
    translateTitle();
  });
  obs.observe(document.body,{childList:true,subtree:true,characterData:true,attributes:true,attributeFilter:ATTRS});
}

