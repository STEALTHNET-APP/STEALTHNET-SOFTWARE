let FRAG_RX = null;
function buildFragments(){
  const esc = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  FRAG_RX = Object.keys(FRAGMENTS)
    .sort((a, b) => b.length - a.length)
    .map(k => {
      // Не даём фрагменту откусить кусок более длинного слова:
      // «Период» не должен превращать «Периодов» в «Periodов».
      const head = CYR.test(k[0]) ? '(?<![А-Яа-яЁё])' : '';
      const tail = CYR.test(k[k.length - 1]) ? '(?![А-Яа-яЁё])' : '';
      return [new RegExp(head + esc(k) + tail, 'g'), FRAGMENTS[k]];
    });
}

function translateFragments(s){
  if (!FRAG_RX) buildFragments();
  let out = s;
  for (const [rx, to] of FRAG_RX) out = out.replace(rx, to);
  for (const [rx, to] of UNITS) out = out.replace(rx, to);
  return out;
}

